export const caseStudies: readonly CaseStudy[] = caseDetails.map((details) => {
  const project = featuredProjects.find((item) => item.slug === details.slug);

  if (!project) {
    throw new Error(`Project data is missing for case: ${details.slug}`);
  }

  return { ...details, title: project.title, project };
});

export function getCaseStudy(slug: string): CaseStudy | undefined {
  return caseStudies.find((caseStudy) => caseStudy.slug === slug);
}
